using System.Text.Json;
using KnowledgeHub.Domain;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Storage.ValueConversion;
using NpgsqlTypes;

namespace KnowledgeHub.Infrastructure.Persistence;

/// <summary>Collections, resources, tags: tables, constraints and indexes from Doc 02 §7.2.</summary>
internal static class LibraryModel
{
    /// <summary>
    /// The weighted search vector: title A, tags B, description C, notes and URL D (Doc 02 §7.2). The URL is split
    /// into words first, because PostgreSQL's parser keeps a whole URL as one token, so a search for "pgbouncer"
    /// would not otherwise find https://pgbouncer.org/docs.
    /// </summary>
    public const string SearchVectorSql = """
        setweight(to_tsvector('english', coalesce(title, '')), 'A') ||
        setweight(to_tsvector('english', coalesce(tags_text, '')), 'B') ||
        setweight(to_tsvector('english', coalesce(description, '')), 'C') ||
        setweight(to_tsvector('english', coalesce(notes, '') || ' ' || regexp_replace(url, '[^[:alnum:]]+', ' ', 'g')), 'D')
        """;

    /// <summary>Stores an enum as its lowercase name (the same text the API uses).</summary>
    private sealed class LowercaseEnum<T>() : ValueConverter<T, string>(
        v => JsonNamingPolicy.SnakeCaseLower.ConvertName(v.ToString()),
        s => Enum.Parse<T>(s.Replace("_", ""), true))
        where T : struct, Enum;

    public static void Configure(ModelBuilder b)
    {
        b.Entity<Collection>(e =>
        {
            e.ToTable("collections");
            e.HasKey(x => x.Id);
            e.Property(x => x.Name).HasMaxLength(100);
            e.Property(x => x.Description).HasMaxLength(500);
            e.Property(x => x.Color).HasMaxLength(20);
            e.Property(x => x.Icon).HasMaxLength(32);
            // The unique (user_id, lower(name)) index cannot be expressed in the model; the migration creates it.
            e.HasIndex(x => new { x.UserId, x.IsPinned, x.Position }).IsDescending(false, true, false);
            e.HasOne<User>().WithMany().HasForeignKey(x => x.UserId).OnDelete(DeleteBehavior.Cascade);
        });

        b.Entity<Resource>(e =>
        {
            e.ToTable("resources", t =>
            {
                t.HasCheckConstraint("ck_resources_type", "type IN ('article','video','pdf','course','repo','website','other')");
                t.HasCheckConstraint("ck_resources_summary_source", "summary_source IN ('none','extracted','ai','user')");
                t.HasCheckConstraint("ck_resources_metadata_status", "metadata_status IN ('pending','ready','failed')");
                t.HasCheckConstraint("ck_resources_metadata_error", "metadata_error IS NULL OR metadata_error IN ('blocked_url','timeout','unreachable','http_error','not_html','too_large','too_many_redirects')");
            });
            e.HasKey(x => x.Id);
            e.Property(x => x.Url).HasMaxLength(2048);
            e.Property(x => x.UrlNormalized).HasMaxLength(2048);
            e.Property(x => x.Title).HasMaxLength(300);
            e.Property(x => x.Description).HasMaxLength(2000);
            e.Property(x => x.Summary).HasMaxLength(2000);
            e.Property(x => x.FaviconUrl).HasMaxLength(2048);
            e.Property(x => x.ImageUrl).HasMaxLength(2048);
            e.Property(x => x.SiteName).HasMaxLength(200);
            e.Property(x => x.TagsText).HasDefaultValue("");
            e.Property(x => x.Type).HasConversion(new LowercaseEnum<ResourceType>()).HasMaxLength(20);
            e.Property(x => x.SummarySource).HasConversion(new LowercaseEnum<SummarySource>()).HasMaxLength(20);
            e.Property(x => x.MetadataStatus).HasConversion(new LowercaseEnum<MetadataStatus>()).HasMaxLength(20);
            e.Property(x => x.MetadataError).HasConversion(new LowercaseEnum<MetadataError>()).HasMaxLength(30);
            e.Property(x => x.UserEditedFields).HasConversion<int>().HasDefaultValue(EditedFields.None);
            e.Property(x => x.ContentHash).HasMaxLength(64);

            // Generated by the database; mapped as a shadow property so the Domain stays free of the driver.
            e.Property<NpgsqlTsVector>("SearchVector").HasColumnType("tsvector").HasComputedColumnSql(SearchVectorSql, stored: true);
            e.HasIndex("SearchVector").HasMethod("gin");

            // Soft delete: trashed resources vanish from every query unless a query asks for them (FR-RES-04).
            e.HasQueryFilter(x => x.DeletedAt == null);
            const string Live = "deleted_at IS NULL";
            e.HasIndex(x => new { x.UserId, x.CreatedAt, x.Id }).IsDescending(false, true, false).HasFilter(Live);
            e.HasIndex(x => new { x.UserId, x.UpdatedAt }).IsDescending(false, true).HasFilter(Live);
            e.HasIndex(x => new { x.UserId, x.CollectionId }).HasFilter(Live);
            e.HasIndex(x => new { x.UserId, x.UrlNormalized }).HasFilter(Live);
            e.HasIndex(x => x.DeletedAt).HasFilter("deleted_at IS NOT NULL"); // finds what to purge

            e.HasOne<User>().WithMany().HasForeignKey(x => x.UserId).OnDelete(DeleteBehavior.Cascade);
            // Restrict: deleting a collection is handled by the application, which asks the user what to do (FR-COL-05).
            e.HasOne<Collection>().WithMany().HasForeignKey(x => x.CollectionId).OnDelete(DeleteBehavior.Restrict);
        });

        b.Entity<Tag>(e =>
        {
            e.ToTable("tags");
            e.HasKey(x => x.Id);
            e.Property(x => x.Name).HasMaxLength(TagNames.MaxLength);
            e.HasIndex(x => new { x.UserId, x.Name }).IsUnique();
            e.HasOne<User>().WithMany().HasForeignKey(x => x.UserId).OnDelete(DeleteBehavior.Cascade);
        });

        b.Entity<ResourceTag>(e =>
        {
            e.ToTable("resource_tags", t => t.HasCheckConstraint("ck_resource_tags_source", "source IN ('user','ai')"));
            e.HasKey(x => new { x.ResourceId, x.TagId });
            e.HasIndex(x => x.TagId);
            e.Property(x => x.Source).HasConversion(new LowercaseEnum<TagSource>()).HasMaxLength(10);
            e.HasOne(x => x.Resource).WithMany(r => r.ResourceTags).HasForeignKey(x => x.ResourceId).OnDelete(DeleteBehavior.Cascade);
            e.HasOne(x => x.Tag).WithMany().HasForeignKey(x => x.TagId).OnDelete(DeleteBehavior.Cascade);
            // Same filter as the resource, so tag counts and tag lists never include the trash.
            e.HasQueryFilter(x => x.Resource.DeletedAt == null);
        });

        b.Entity<OutboxMessage>(e =>
        {
            e.ToTable("outbox", t => t.HasCheckConstraint("ck_outbox_status", "status IN ('pending','processing','done','dead')"));
            e.HasKey(x => x.Id);
            e.Property(x => x.Type).HasMaxLength(60);
            e.Property(x => x.Payload).HasColumnType("jsonb");
            e.Property(x => x.Traceparent).HasMaxLength(100);
            e.Property(x => x.Status).HasConversion(new LowercaseEnum<OutboxStatus>()).HasMaxLength(12);
            e.Property(x => x.LastError).HasMaxLength(2000);
            e.HasIndex(x => x.NextAttemptAt).HasFilter("status = 'pending'"); // what the worker polls
            e.HasIndex(x => new { x.Status, x.ProcessedAt }); // clean-up
        });
    }
}
